use serde::{Deserialize, Serialize};
use ts_rs::TS;

use crate::driver::Row;
use crate::sql::Dialect;

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "camelCase")]
#[ts(export)]
pub struct TableTarget {
    pub database: String,
    pub schema: Option<String>,
    pub table: String,
}

impl TableTarget {
    pub fn qualified(&self, dialect: Dialect) -> String {
        match (dialect, &self.schema) {
            (Dialect::Postgres { .. }, Some(schema)) => dialect.qualified(&[schema, &self.table]),
            (Dialect::Postgres { .. }, None) => dialect.quote_ident(&self.table),
            (Dialect::MySql { .. }, _) => dialect.qualified(&[&self.database, &self.table]),
        }
    }

    fn regclass(&self, dialect: Dialect) -> String {
        format!(
            "{}::regclass",
            dialect.quote_literal(&self.qualified(dialect))
        )
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, TS)]
#[serde(rename_all = "snake_case")]
#[ts(export)]
pub enum ObjectKind {
    Table,
    View,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, TS)]
#[serde(rename_all = "camelCase")]
#[ts(export)]
pub struct DbObject {
    pub name: String,
    pub kind: ObjectKind,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, TS)]
#[serde(rename_all = "camelCase")]
#[ts(export)]
pub struct ColumnInfo {
    pub name: String,
    pub data_type: String,
    pub nullable: bool,
    pub default: Option<String>,
    pub extra: Option<String>,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, TS)]
#[serde(rename_all = "camelCase")]
#[ts(export)]
pub struct TableKey {
    pub name: String,
    pub primary: bool,
    pub columns: Vec<String>,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, TS)]
#[serde(rename_all = "camelCase")]
#[ts(export)]
pub struct TableInfo {
    pub columns: Vec<ColumnInfo>,
    pub keys: Vec<TableKey>,
    pub editable_key: Option<Vec<String>>,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, TS)]
#[serde(rename_all = "camelCase")]
#[ts(export)]
pub struct CompletionTable {
    pub schema: String,
    pub table: String,
    pub columns: Vec<String>,
}

pub(crate) fn databases_sql(dialect: Dialect) -> &'static str {
    match dialect {
        Dialect::MySql { .. } => "SHOW DATABASES",
        Dialect::Postgres { .. } => {
            "SELECT datname FROM pg_database WHERE NOT datistemplate AND datallowconn ORDER BY datname"
        }
    }
}

pub(crate) const PG_SCHEMAS_SQL: &str = "SELECT nspname FROM pg_namespace WHERE nspname NOT LIKE 'pg!_%' ESCAPE '!' AND nspname <> 'information_schema' ORDER BY nspname";

pub(crate) fn objects_sql(dialect: Dialect, database: &str, schema: Option<&str>) -> String {
    match dialect {
        Dialect::MySql { .. } => format!(
            "SELECT TABLE_NAME, TABLE_TYPE FROM information_schema.TABLES WHERE TABLE_SCHEMA = {} ORDER BY TABLE_NAME",
            dialect.quote_literal(database)
        ),
        Dialect::Postgres { .. } => format!(
            "SELECT c.relname, c.relkind FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace WHERE n.nspname = {} AND c.relkind IN ('r', 'p', 'f', 'v', 'm') ORDER BY c.relname",
            dialect.quote_literal(schema.unwrap_or("public"))
        ),
    }
}

pub(crate) fn parse_objects(dialect: Dialect, rows: Vec<Row>) -> Vec<DbObject> {
    rows.into_iter()
        .filter_map(|row| {
            let mut cells = row.into_iter();
            let name = cells.next().flatten()?;
            let kind_text = cells.next().flatten().unwrap_or_default();
            let view = match dialect {
                Dialect::MySql { .. } => kind_text.contains("VIEW"),
                Dialect::Postgres { .. } => kind_text == "v" || kind_text == "m",
            };
            Some(DbObject {
                name,
                kind: if view {
                    ObjectKind::View
                } else {
                    ObjectKind::Table
                },
            })
        })
        .collect()
}

pub(crate) fn columns_sql(dialect: Dialect, target: &TableTarget) -> String {
    match dialect {
        Dialect::MySql { .. } => format!(
            "SELECT COLUMN_NAME, COLUMN_TYPE, IS_NULLABLE, COLUMN_DEFAULT, EXTRA FROM information_schema.COLUMNS WHERE TABLE_SCHEMA = {} AND TABLE_NAME = {} ORDER BY ORDINAL_POSITION",
            dialect.quote_literal(&target.database),
            dialect.quote_literal(&target.table)
        ),
        Dialect::Postgres { .. } => format!(
            "SELECT a.attname, format_type(a.atttypid, a.atttypmod), CASE WHEN a.attnotnull THEN 'NO' ELSE 'YES' END, pg_get_expr(d.adbin, d.adrelid), CASE a.attidentity WHEN 'a' THEN 'GENERATED ALWAYS AS IDENTITY' WHEN 'd' THEN 'GENERATED BY DEFAULT AS IDENTITY' ELSE CASE a.attgenerated WHEN 's' THEN 'STORED GENERATED' WHEN 'v' THEN 'VIRTUAL GENERATED' ELSE NULL END END FROM pg_attribute a LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum WHERE a.attrelid = {} AND a.attnum > 0 AND NOT a.attisdropped ORDER BY a.attnum",
            target.regclass(dialect)
        ),
    }
}

pub(crate) fn parse_columns(rows: Vec<Row>) -> Vec<ColumnInfo> {
    rows.into_iter()
        .filter_map(|row| {
            let mut cells = row.into_iter();
            let name = cells.next().flatten()?;
            let data_type = cells.next().flatten().unwrap_or_default();
            let nullable = cells.next().flatten().is_some_and(|value| value == "YES");
            let default = cells.next().flatten();
            let extra = cells.next().flatten().filter(|value| !value.is_empty());
            Some(ColumnInfo {
                name,
                data_type,
                nullable,
                default,
                extra,
            })
        })
        .collect()
}

pub(crate) fn keys_sql(dialect: Dialect, target: &TableTarget) -> String {
    match dialect {
        Dialect::MySql { .. } => format!(
            "SELECT INDEX_NAME, CASE WHEN INDEX_NAME = 'PRIMARY' THEN 'YES' ELSE 'NO' END, COLUMN_NAME FROM information_schema.STATISTICS WHERE TABLE_SCHEMA = {} AND TABLE_NAME = {} AND NON_UNIQUE = 0 ORDER BY INDEX_NAME = 'PRIMARY' DESC, INDEX_NAME, SEQ_IN_INDEX",
            dialect.quote_literal(&target.database),
            dialect.quote_literal(&target.table)
        ),
        Dialect::Postgres { .. } => format!(
            "SELECT ic.relname, CASE WHEN i.indisprimary THEN 'YES' ELSE 'NO' END, a.attname FROM pg_index i JOIN pg_class ic ON ic.oid = i.indexrelid CROSS JOIN LATERAL unnest(i.indkey::int2[]) WITH ORDINALITY AS k(attnum, ord) LEFT JOIN pg_attribute a ON a.attrelid = i.indrelid AND a.attnum = k.attnum WHERE i.indrelid = {} AND (i.indisprimary OR i.indisunique) AND i.indpred IS NULL AND k.ord <= i.indnkeyatts ORDER BY i.indisprimary DESC, ic.relname, k.ord",
            target.regclass(dialect)
        ),
    }
}

pub(crate) fn parse_keys(rows: Vec<Row>) -> Vec<TableKey> {
    let mut keys: Vec<(TableKey, bool)> = Vec::new();
    for row in rows {
        let mut cells = row.into_iter();
        let Some(name) = cells.next().flatten() else {
            continue;
        };
        let primary = cells.next().flatten().is_some_and(|value| value == "YES");
        let column = cells.next().flatten();
        let index = match keys.iter().position(|(key, _)| key.name == name) {
            Some(index) => index,
            None => {
                keys.push((
                    TableKey {
                        name,
                        primary,
                        columns: Vec::new(),
                    },
                    true,
                ));
                keys.len() - 1
            }
        };
        let (key, usable) = &mut keys[index];
        match column {
            Some(column) => key.columns.push(column),
            None => *usable = false,
        }
    }
    keys.into_iter()
        .filter(|(key, usable)| *usable && !key.columns.is_empty())
        .map(|(key, _)| key)
        .collect()
}

pub(crate) fn editable_key(columns: &[ColumnInfo], keys: &[TableKey]) -> Option<Vec<String>> {
    if let Some(primary) = keys.iter().find(|key| key.primary) {
        return Some(primary.columns.clone());
    }
    keys.iter()
        .find(|key| {
            key.columns.iter().all(|name| {
                columns
                    .iter()
                    .any(|column| &column.name == name && !column.nullable)
            })
        })
        .map(|key| key.columns.clone())
}

pub(crate) fn completion_sql(dialect: Dialect, database: &str) -> String {
    match dialect {
        Dialect::MySql { .. } => format!(
            "SELECT TABLE_SCHEMA, TABLE_NAME, COLUMN_NAME FROM information_schema.COLUMNS WHERE TABLE_SCHEMA = {} ORDER BY TABLE_NAME, ORDINAL_POSITION",
            dialect.quote_literal(database)
        ),
        Dialect::Postgres { .. } => "SELECT table_schema, table_name, column_name FROM information_schema.columns WHERE table_schema NOT IN ('pg_catalog', 'information_schema') ORDER BY table_schema, table_name, ordinal_position".to_string(),
    }
}

pub(crate) fn parse_completion(rows: Vec<Row>) -> Vec<CompletionTable> {
    let mut tables: Vec<CompletionTable> = Vec::new();
    for row in rows {
        let mut cells = row.into_iter();
        let (Some(schema), Some(table), Some(column)) = (
            cells.next().flatten(),
            cells.next().flatten(),
            cells.next().flatten(),
        ) else {
            continue;
        };
        match tables.last_mut() {
            Some(last) if last.schema == schema && last.table == table => last.columns.push(column),
            _ => tables.push(CompletionTable {
                schema,
                table,
                columns: vec![column],
            }),
        }
    }
    tables
}

pub(crate) fn mysql_ddl_sql(dialect: Dialect, target: &TableTarget) -> String {
    format!("SHOW CREATE TABLE {}", target.qualified(dialect))
}

pub(crate) fn pg_relkind_sql(dialect: Dialect, target: &TableTarget) -> String {
    format!(
        "SELECT relkind, CASE WHEN relkind IN ('v', 'm') THEN pg_get_viewdef(oid, true) END FROM pg_class WHERE oid = {}",
        target.regclass(dialect)
    )
}

pub(crate) fn pg_constraints_sql(dialect: Dialect, target: &TableTarget) -> String {
    format!(
        "SELECT conname, pg_get_constraintdef(oid, true) FROM pg_constraint WHERE conrelid = {} AND contype IN ('p', 'u', 'f', 'c', 'x') ORDER BY CASE contype WHEN 'p' THEN 0 WHEN 'u' THEN 1 WHEN 'f' THEN 2 ELSE 3 END, conname",
        target.regclass(dialect)
    )
}

pub(crate) fn pg_indexes_sql(dialect: Dialect, target: &TableTarget) -> String {
    format!(
        "SELECT pg_get_indexdef(i.indexrelid) FROM pg_index i WHERE i.indrelid = {} AND NOT EXISTS (SELECT 1 FROM pg_constraint c WHERE c.conindid = i.indexrelid) ORDER BY 1",
        target.regclass(dialect)
    )
}

pub(crate) fn pg_table_ddl(
    dialect: Dialect,
    target: &TableTarget,
    columns: &[ColumnInfo],
    constraints: Vec<Row>,
    indexes: Vec<Row>,
) -> String {
    let mut lines: Vec<String> = columns
        .iter()
        .map(|column| {
            let mut line = format!(
                "    {} {}",
                dialect.quote_ident(&column.name),
                column.data_type
            );
            match column.extra.as_deref() {
                Some(generated) if generated.ends_with("GENERATED") => {
                    let mode = if generated.starts_with("VIRTUAL") {
                        "VIRTUAL"
                    } else {
                        "STORED"
                    };
                    line.push_str(&format!(
                        " GENERATED ALWAYS AS ({}) {mode}",
                        column.default.as_deref().unwrap_or_default()
                    ));
                }
                Some(identity) => {
                    line.push(' ');
                    line.push_str(identity);
                }
                None => {
                    if let Some(default) = &column.default {
                        line.push_str(&format!(" DEFAULT {default}"));
                    }
                }
            }
            if !column.nullable {
                line.push_str(" NOT NULL");
            }
            line
        })
        .collect();
    for row in constraints {
        let mut cells = row.into_iter();
        if let (Some(name), Some(definition)) = (cells.next().flatten(), cells.next().flatten()) {
            lines.push(format!(
                "    CONSTRAINT {} {definition}",
                dialect.quote_ident(&name)
            ));
        }
    }
    let mut ddl = format!(
        "CREATE TABLE {} (\n{}\n);",
        target.qualified(dialect),
        lines.join(",\n")
    );
    for row in indexes {
        if let Some(Some(definition)) = row.into_iter().next() {
            ddl.push_str(&format!("\n\n{definition};"));
        }
    }
    ddl
}

#[cfg(test)]
mod tests {
    use super::*;

    fn row(cells: &[Option<&str>]) -> Row {
        cells.iter().map(|cell| cell.map(str::to_string)).collect()
    }

    fn column(name: &str, nullable: bool) -> ColumnInfo {
        ColumnInfo {
            name: name.into(),
            data_type: "int".into(),
            nullable,
            default: None,
            extra: None,
        }
    }

    #[test]
    fn groups_key_columns_and_drops_expression_keys() {
        let keys = parse_keys(vec![
            row(&[Some("PRIMARY"), Some("YES"), Some("a")]),
            row(&[Some("PRIMARY"), Some("YES"), Some("b")]),
            row(&[Some("uq_expr"), Some("NO"), None]),
            row(&[Some("uq_email"), Some("NO"), Some("email")]),
        ]);
        assert_eq!(keys.len(), 2);
        assert_eq!(keys[0].columns, vec!["a", "b"]);
        assert!(keys[0].primary);
        assert_eq!(keys[1].name, "uq_email");
    }

    #[test]
    fn editable_key_prefers_primary_then_not_null_unique() {
        let columns = vec![
            column("id", false),
            column("email", true),
            column("code", false),
        ];
        let unique = |name: &str, col: &str| TableKey {
            name: name.into(),
            primary: false,
            columns: vec![col.into()],
        };
        assert_eq!(
            editable_key(
                &columns,
                &[unique("uq_email", "email"), unique("uq_code", "code")]
            ),
            Some(vec!["code".to_string()])
        );
        assert_eq!(editable_key(&columns, &[unique("uq_email", "email")]), None);
        let primary = TableKey {
            name: "pk".into(),
            primary: true,
            columns: vec!["id".into()],
        };
        assert_eq!(
            editable_key(&columns, &[unique("uq_code", "code"), primary]),
            Some(vec!["id".to_string()])
        );
    }

    #[test]
    fn qualifies_targets_per_dialect() {
        let target = TableTarget {
            database: "shop".into(),
            schema: Some("sales".into()),
            table: "orders".into(),
        };
        assert_eq!(target.qualified(Dialect::MYSQL), "`shop`.`orders`");
        assert_eq!(target.qualified(Dialect::POSTGRES), "\"sales\".\"orders\"");
        assert_eq!(
            target.regclass(Dialect::POSTGRES),
            "'\"sales\".\"orders\"'::regclass"
        );
    }

    #[test]
    fn builds_postgres_table_ddl() {
        let target = TableTarget {
            database: "app".into(),
            schema: Some("public".into()),
            table: "users".into(),
        };
        let columns = vec![
            ColumnInfo {
                name: "id".into(),
                data_type: "integer".into(),
                nullable: false,
                default: None,
                extra: Some("GENERATED BY DEFAULT AS IDENTITY".into()),
            },
            ColumnInfo {
                name: "name".into(),
                data_type: "text".into(),
                nullable: true,
                default: Some("'x'::text".into()),
                extra: None,
            },
        ];
        let ddl = pg_table_ddl(
            Dialect::POSTGRES,
            &target,
            &columns,
            vec![row(&[Some("users_pkey"), Some("PRIMARY KEY (id)")])],
            vec![row(&[Some(
                "CREATE INDEX users_name ON public.users USING btree (name)",
            )])],
        );
        assert_eq!(
            ddl,
            "CREATE TABLE \"public\".\"users\" (\n    \"id\" integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,\n    \"name\" text DEFAULT 'x'::text,\n    CONSTRAINT \"users_pkey\" PRIMARY KEY (id)\n);\n\nCREATE INDEX users_name ON public.users USING btree (name);"
        );
    }

    #[test]
    fn groups_completion_rows() {
        let tables = parse_completion(vec![
            row(&[Some("public"), Some("a"), Some("x")]),
            row(&[Some("public"), Some("a"), Some("y")]),
            row(&[Some("public"), Some("b"), Some("z")]),
        ]);
        assert_eq!(tables.len(), 2);
        assert_eq!(tables[0].columns, vec!["x", "y"]);
    }
}
